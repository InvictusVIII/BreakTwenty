#!/usr/bin/env node
/*
 * generate-theme-css.js — compiles the design-token single source of truth
 * (src/theme/colors.js `breaktwentyCssVariables` + src/theme/surfaces.js
 * `breaktwentySurfaceCssVariables` + src/theme/typography.js
 * `breaktwentyTypographyCssVariables`) into src/theme/tokens.generated.css, the
 * static :root mirror that covers the first paint before the runtime
 * installers (applyBreakTwentyTheme/applyBreakTwentySurfaces/applyBreakTwentyTypography) take over.
 *
 * Wired into `npm start` and `npm run build` (see package.json), and runnable
 * directly via `npm run generate:theme`. `npm run generate:theme:check` and
 * src/theme/tokenParity.test.js fail if the committed generated file is stale
 * relative to the JS maps.
 *
 * The theme modules are ESM inside a CommonJS package, so this script loads
 * them by stripping `export ` and evaluating in a VM sandbox — which is why
 * src/theme/colors.js, src/theme/surfaces.js, and src/theme/typography.js MUST stay dependency-free
 * (no import statements).
 */

'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');

const THEME_DIR = path.join(__dirname, '..', 'src', 'theme');
const OUTPUT_FILE = path.join(THEME_DIR, 'tokens.generated.css');

function loadThemeModule(fileName, exportNames) {
  const filePath = path.join(THEME_DIR, fileName);
  const source = fs.readFileSync(filePath, 'utf8');
  if (/^\s*import\s/m.test(source)) {
    throw new Error(
      `${fileName} contains an import statement; theme token modules must stay ` +
      'dependency-free so generate-theme-css.js can evaluate them standalone.'
    );
  }
  const sandbox = { __collected: {} };
  const script =
    source.replace(/^export\s+/gm, '') +
    `\n__collected = { ${exportNames.join(', ')} };`;
  vm.runInNewContext(script, sandbox, { filename: fileName });
  return sandbox.__collected;
}

function serializeThemeCss(tokenMap) {
  const lines = Object.entries(tokenMap).map(
    ([name, value]) => `  ${name}: ${String(value).trim()};`
  );
  return [
    '/* AUTO-GENERATED by scripts/generate-theme-css.js — DO NOT EDIT.',
    ' * Single source of truth: src/theme/colors.js (breaktwentyCssVariables) +',
    ' * src/theme/surfaces.js (breaktwentySurfaceCssVariables) +',
    ' * src/theme/typography.js (breaktwentyTypographyCssVariables).',
    ' * Regenerate: npm run generate:theme (runs automatically on start/build).',
    ' * Guard: src/theme/tokenParity.test.js fails when this file is stale. */',
    ':root {',
    ...lines,
    '}',
    '',
  ].join('\n');
}

function buildTokenMap() {
  const { breaktwentyCssVariables } = loadThemeModule('colors.js', ['breaktwentyCssVariables']);
  const { breaktwentySurfaceCssVariables } = loadThemeModule('surfaces.js', [
    'breaktwentySurfaceCssVariables',
  ]);
  const { breaktwentyTypographyCssVariables } = loadThemeModule('typography.js', [
    'breaktwentyTypographyCssVariables',
  ]);
  return { ...breaktwentyCssVariables, ...breaktwentySurfaceCssVariables, ...breaktwentyTypographyCssVariables };
}

function main() {
  const check = new Set(process.argv.slice(2)).has('--check');
  const tokenMap = buildTokenMap();
  const tokenCount = Object.keys(tokenMap).length;
  if (tokenCount < 80) {
    throw new Error(`Suspiciously few tokens collected (${tokenCount}); aborting.`);
  }
  const css = serializeThemeCss(tokenMap);
  const previous = fs.existsSync(OUTPUT_FILE) ? fs.readFileSync(OUTPUT_FILE, 'utf8') : null;
  if (previous === css) {
    console.log(`theme tokens: up to date (${tokenCount} tokens).`);
    return;
  }
  if (check) {
    throw new Error(
      'Theme token mirror is out of sync. Run "npm run generate:theme" from the frontend directory.'
    );
  }
  fs.writeFileSync(OUTPUT_FILE, css);
  console.log(`theme tokens: wrote ${path.relative(process.cwd(), OUTPUT_FILE)} (${tokenCount} tokens).`);
}

module.exports = { buildTokenMap, serializeThemeCss, OUTPUT_FILE };

if (require.main === module) {
  main();
}
